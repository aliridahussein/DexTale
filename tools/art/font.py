def build(scale=1, name="dawnmere"):
    chars = sorted(G.keys(), key=ord)
    cols = 16
    cell_w = 7 * scale
    cell_h = H * scale
    rows = (len(chars) + cols - 1) // cols
    W = cols * (cell_w + 1)
    Hh = rows * (cell_h + 1)
    img = Image.new("RGBA", (W, Hh), (0, 0, 0, 0))
    lines = []
    for i, ch in enumerate(chars):
        top, rws = G[ch]
        w = max(len(r) for r in rws)
        cx = (i % cols) * (cell_w + 1)
        cy = (i // cols) * (cell_h + 1)
        for ry, r in enumerate(rws):
            for rx, c in enumerate(r):
                if c == "#":
                    for sy in range(scale):
                        for sx in range(scale):
                            img.putpixel((cx + rx * scale + sx, cy + (top + ry) * scale + sy), (255, 255, 255, 255))
        adv = (w + 1) * scale
        lines.append(f"char id={ord(ch)} x={cx} y={cy} width={w * scale} height={cell_h} xoffset=0 yoffset=0 xadvance={adv} page=0 chnl=15")
    lines.append(f"char id=32 x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 xadvance={3 * scale} page=0 chnl=15")
    lines.append(f"char id=160 x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 xadvance={3 * scale} page=0 chnl=15")
    out_dir = os.path.join(ROOT, "assets", "fonts")
    os.makedirs(out_dir, exist_ok=True)
    img.save(os.path.join(out_dir, f"{name}.png"))
    header = [
        f'info face="Dawnmere" size={H * scale} bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=1,1 outline=0',
        f"common lineHeight={LINE * scale} base={BASE * scale} scaleW={W} scaleH={Hh} pages=1 packed=0 alphaChnl=0 redChnl=4 greenChnl=4 blueChnl=4",
        f'page id=0 file="{name}.png"',
        f"chars count={len(lines)}",
    ]
    with open(os.path.join(out_dir, f"{name}.fnt"), "w", newline="\n") as f:
        f.write("\n".join(header + lines) + "\nkernings count=0\n")
    return len(lines)


